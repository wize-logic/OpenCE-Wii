#!/usr/bin/env python3
"""Links the Wii build (``ninja wii``) while its platform layer is incomplete.

The game calls far more of the platform layer (the Xbox APIs the port
emulates) than port/wii/src provides yet. This links the executable once; if
the linker reports undefined symbols, it writes a C file defining each one
as a function that stops the game naming it (wii_missing_symbol,
port/wii/src/wii_boot.c), compiles it, and links again. The list goes to
--report, one name a line: what the Wii port still lacks. A data symbol
stubbed this way is a function, which is wrong, and only safe because the
game stops as soon as it calls into any of them. Once the list is empty
this is an ordinary link.

usage: wii_link.py --linker CC --compiler CC --cflags FLAGS --ldflags FLAGS
                   --libs FLAGS --stubs FILE.c --report FILE.txt
                   --output FILE.elf @objects.rsp
"""

import argparse
import re
import shlex
import subprocess
import sys
from pathlib import Path

UNDEFINED = re.compile(r"undefined reference to `([^']+)'")
IDENTIFIER = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")


def link(linker, ldflags, objects, libs, output):
    command = [*shlex.split(linker), *shlex.split(ldflags), "-o", str(output), *objects, *shlex.split(libs)]
    return subprocess.run(command, capture_output=True, text=True)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--linker", required=True)
    parser.add_argument("--compiler", required=True)
    parser.add_argument("--cflags", default="")
    parser.add_argument("--ldflags", default="")
    parser.add_argument("--libs", default="")
    parser.add_argument("--stubs", type=Path, required=True)
    parser.add_argument("--report", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("objects", nargs="*")
    args = parser.parse_args()
    # (ninja's response file quotes the paths with spaces, as a shell would)
    args.objects = [obj for argument in args.objects
                    for obj in (shlex.split(Path(argument[1:]).read_text()) if argument.startswith("@") else [argument])]

    result = link(args.linker, args.ldflags, args.objects, args.libs, args.output)
    missing = sorted(set(UNDEFINED.findall(result.stderr)))
    if result.returncode == 0:
        args.report.write_text("")
        return 0
    stubbable = [name for name in missing if IDENTIFIER.match(name)]
    if not missing or len(stubbable) != len(missing):
        # (a failure that is not only undefined symbols)
        sys.stderr.write(result.stderr)
        return result.returncode or 1

    lines = ["/* generated by tools/wii_link.py: the platform symbols port/wii does not provide yet */",
             "", "void wii_missing_symbol(const char *name) __attribute__((noreturn));", ""]
    for name in stubbable:
        lines.append(f'void {name}(void) {{ wii_missing_symbol("{name}"); }}')
    args.stubs.write_text("\n".join(lines) + "\n")
    stub_object = args.stubs.with_suffix(".o")
    compiled = subprocess.run([*shlex.split(args.compiler), *shlex.split(args.cflags), "-w", "-c",
                               str(args.stubs), "-o", str(stub_object)], capture_output=True, text=True)
    if compiled.returncode != 0:
        sys.stderr.write(compiled.stderr)
        return compiled.returncode

    result = link(args.linker, args.ldflags, [*args.objects, str(stub_object)], args.libs, args.output)
    if result.returncode != 0:
        sys.stderr.write(result.stderr)
        return result.returncode
    args.report.write_text("".join(f"{name}\n" for name in stubbable))
    print(f"wii_link.py: {len(stubbable)} platform symbols stubbed (listed in {args.report})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
